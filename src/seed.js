export function seedPortfolio(store, { reset = false } = {}) {
  if (reset) {
    store.resetAll();
  }
  if (store.countAccounts() > 0) {
    return {
      seeded: false,
      accounts: store.countAccounts(),
    };
  }

  for (const acct of SEED_ACCOUNTS) {
    // Normalize capitalization on names
    const normalizedName =
      acct.name.charAt(0).toUpperCase() + acct.name.slice(1);
    store.upsertAccount({ ...acct, name: normalizedName });
  }

  for (const evt of INITIAL_EVENTS) {
    store.ingestEvent(evt);
  }

  return {
    seeded: true,
    accounts: store.countAccounts(),
    owners: OWNERS,
  };
}

